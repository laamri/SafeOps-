-- Baseline of the schema Hibernate created before Flyway took over. Existing databases are
-- marked as baselined (see spring.flyway.baseline-on-migrate) so this script only runs on a
-- fresh database; it must therefore match the entities exactly.

CREATE TABLE establishment (
    id varchar(255) NOT NULL,
    address varchar(255),
    category varchar(255),
    city varchar(255),
    closes_at varchar(255),
    color varchar(255),
    name varchar(255),
    opens_at varchar(255),
    short_name varchar(255),
    tint varchar(255),
    organization_id varchar(64),
    CONSTRAINT establishment_pkey PRIMARY KEY (id)
);

CREATE TABLE service_queue (
    id bigint NOT NULL,
    avg_service_minutes integer NOT NULL,
    counter varchar(255),
    last_number integer NOT NULL,
    name varchar(255),
    prefix varchar(255),
    establishment_id varchar(255) NOT NULL,
    is_open boolean,
    CONSTRAINT service_queue_pkey PRIMARY KEY (id),
    CONSTRAINT fke4ponlayde9xauy04888my6bw FOREIGN KEY (establishment_id) REFERENCES establishment (id)
);

ALTER TABLE service_queue ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME service_queue_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1);

CREATE TABLE ticket (
    id uuid NOT NULL,
    called_at timestamp(6) with time zone,
    closed_at timestamp(6) with time zone,
    code varchar(255),
    created_at timestamp(6) with time zone,
    number integer NOT NULL,
    owner_name varchar(255),
    owner_subject varchar(255),
    status varchar(255),
    queue_id bigint NOT NULL,
    organization_id varchar(64),
    CONSTRAINT ticket_pkey PRIMARY KEY (id),
    CONSTRAINT ticket_status_check CHECK (status IN ('WAITING', 'CALLED', 'SERVED', 'NO_SHOW', 'CANCELLED')),
    CONSTRAINT fkr24wfrsehm8ym031nf7o3bg29 FOREIGN KEY (queue_id) REFERENCES service_queue (id)
);

