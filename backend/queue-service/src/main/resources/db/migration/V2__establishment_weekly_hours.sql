-- Weekly opening hours per establishment, and the suspension flag.
-- Opening hours are an establishment-level calendar: each row is one opening interval, so a
-- day with a lunch break has two rows. day_of_week follows ISO-8601 (1 = Monday, 7 = Sunday).

ALTER TABLE establishment ADD COLUMN active boolean NOT NULL DEFAULT true;

CREATE TABLE weekly_hours (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    establishment_id varchar(255) NOT NULL,
    day_of_week smallint NOT NULL,
    opens_at time NOT NULL,
    closes_at time NOT NULL,
    CONSTRAINT weekly_hours_pkey PRIMARY KEY (id),
    CONSTRAINT weekly_hours_establishment_fk FOREIGN KEY (establishment_id)
        REFERENCES establishment (id) ON DELETE CASCADE,
    CONSTRAINT weekly_hours_day_check CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT weekly_hours_range_check CHECK (opens_at < closes_at)
);

CREATE INDEX idx_weekly_hours_establishment_day ON weekly_hours (establishment_id, day_of_week);
